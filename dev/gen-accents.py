#!/usr/bin/env python3
"""Writes crates/rustpress-core/src/accents_table.rs from `remove_accents()` of the reference's formatting.php.

    python dev/gen-accents.py"""
import re

SOURCE = r'\\wsl.localhost\Debian\home\yoshi\.local\share\containers\storage\volumes\rustpress-wp\_data\wp-includes\formatting.php'
TARGET = 'crates/rustpress-core/src/accents_table.rs'

php = open(SOURCE, encoding='utf-8').read()
body = php[php.index('function remove_accents('):]
table = body[body.index('$chars = array('):]
table = table[:table.index(');')]
pairs = re.findall(r"^\s*'((?:[^'\\]|\\.)+)'\s*=>\s*'((?:[^'\\]|\\.)*)',", table, re.M)


def rust(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')


with open(TARGET, 'w', encoding='utf-8', newline='\n') as out:
    out.write('//! The table of `remove_accents()` (generated by `dev/gen-accents.py` from WordPress\'s formatting.php).\n\n')
    out.write('pub(crate) const ACCENTS: &[(char, &str)] = &[\n')
    for key, value in pairs:
        assert len(key) == 1, key
        out.write(f'    (\'{rust(key)}\', "{rust(value)}"),\n')
    out.write('];\n')
print(len(pairs), 'pairs')
