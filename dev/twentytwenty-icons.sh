#!/usr/bin/env bash
# Writes crates/rustpress-theme/src/classic/twentytwenty_icons.rs: the icons of Twenty Twenty as the theme's
# twentytwenty_get_theme_svg() returns them, asked from the reference (the theme must be in wp-content/themes).
# Usage: dev/twentytwenty-icons.sh
set -euo pipefail
cd "$(dirname "$0")/.."
snippet=$(mktemp)
trap 'rm -f "$snippet"' EXIT
cat > "$snippet" <<'PHP'
<?php
$t = '/var/www/html/wp-content/themes/twentytwenty';
require_once $t . '/classes/class-twentytwenty-svg-icons.php';
require_once $t . '/inc/svg-icons.php';
$r = new ReflectionClass('TwentyTwenty_SVG_Icons');
$q = function ($s) { return '"' . addcslashes($s, "\"\\") . '"'; };
echo "//! The icons of `TwentyTwenty_SVG_Icons` as `twentytwenty_get_theme_svg()` returns them (through `wp_kses()`),\n//! generated by `dev/twentytwenty-icons.sh` from `classes/class-twentytwenty-svg-icons.php` of Twenty Twenty 3.3.\n\n";
foreach (array('ui' => 'UI', 'social' => 'SOCIAL') as $group => $name) {
	$prop = $group === 'ui' ? 'ui_icons' : 'social_icons';
	echo "pub(super) const $name: &[(&str, &str)] = &[\n";
	foreach (array_keys($r->getStaticPropertyValue($prop)) as $icon) {
		echo "    (" . $q($icon) . ", " . $q(twentytwenty_get_theme_svg($icon, $group)) . "),\n";
	}
	echo "];\n\n";
}
echo "/// `TwentyTwenty_SVG_Icons::\$social_icons_map`.\npub(super) const SOCIAL_MAP: &[(&str, &[&str])] = &[\n";
foreach ($r->getStaticPropertyValue('social_icons_map') as $icon => $domains) {
	echo "    (" . $q($icon) . ", &[" . implode(', ', array_map($q, $domains)) . "]),\n";
}
echo "];\n";
PHP
dev/php.sh "$snippet" > crates/rustpress-theme/src/classic/twentytwenty_icons.rs
