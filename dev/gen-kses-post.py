#!/usr/bin/env python3
"""Writes crates/rustpress-core/src/kses_post_table.rs from `wp_kses_allowed_html('post')` of the reference (WSL, WP-CLI).

    python dev/gen-kses-post.py"""
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
php = 'echo json_encode(wp_kses_allowed_html("post")), "\n";'
raw = subprocess.run(['wsl.exe', '-d', 'Debian', '--', 'bash', '-c', f"printf %s '{php}' | bash /mnt/c/work/experimental/rustpress/dev/wp-eval.sh"], capture_output=True, text=True, encoding='utf-8').stdout
data = json.loads(raw)
lines = [
    "//! `wp_kses_allowed_html( 'post' )`: the tags and attributes of post content. Generated by `dev/gen-kses-post.py` from the",
    '//! reference WordPress; `data-*` stands for every data attribute, `download` must be valueless, `object` takes only',
    '//! PDF files of the site (`_wp_kses_allow_pdf_objects`).',
    '',
    '/// `(element, attributes)` in the order of WordPress.',
    'pub const ALLOWED_POST: &[(&str, &[&str])] = &[',
]
for tag, attrs in data.items():
    lines.append('    ("%s", &[%s]),' % (tag, ', '.join('"%s"' % a for a in attrs)))
lines.append('];')
with open(os.path.join(HERE, '..', 'crates', 'rustpress-core', 'src', 'kses_post_table.rs'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines) + '\n')
print(len(data), 'tags')
